/**
 * 重启 DeepSeek Harness 的实现层。
 *
 * 三层策略，从最干净的一层往下退：
 *   1. 桌面运行时服务（ctx.get('desktopRuntime').requestRestart）——Electron 自己 relaunch
 *   2. 桌面安装：写一个 wscript 脱离进程树，杀掉同路径的全部 exe，再重新拉起
 *   3. 都不成立：返回明确失败，让调用方提示手动重启
 *
 * 第 2 层的关键点：Host 进程本身是 ELECTRON_RUN_AS_NODE 模式跑起来的
 * `DeepSeek Harness.exe`，和 GUI 主进程同名同路径。所以「重启」= 按 ExecutablePath
 * 精确匹配、把所有同名进程结束掉，再启动一个干净的 GUI。
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync, spawn } from 'node:child_process'

/** 桌面安装的镜像名，按官方安装器与历史命名。 */
const EXE_NAMES = Object.freeze(['DeepSeek Harness.exe', 'DSH Desktop.exe'])

function matchesExeName(value) {
  const base = path.basename(String(value || '')).toLowerCase()
  return EXE_NAMES.some((name) => name.toLowerCase() === base)
}

/** Harness 数据根，日志写在它下面，出问题好翻。 */
export function dshHome() {
  const fromEnv = process.env.DSH_HOME
  if (typeof fromEnv === 'string' && fromEnv.trim()) return fromEnv.trim()
  return path.join(os.homedir(), '.dsh')
}

/** 桌面 exe 的绝对路径；找不到返回空串，调用方据此降级。 */
export function desktopExecutable() {
  const exec = process.execPath
  if (exec && matchesExeName(exec) && fs.existsSync(exec)) return path.normalize(exec)

  const resources = process.resourcesPath
  if (resources) {
    const dir = path.dirname(resources)
    for (const name of EXE_NAMES) {
      const candidate = path.join(dir, name)
      if (fs.existsSync(candidate)) return path.normalize(candidate)
    }
  }

  for (const arg of process.argv) {
    if (typeof arg === 'string' && matchesExeName(arg) && fs.existsSync(arg)) {
      return path.normalize(arg)
    }
  }
  return ''
}

function desktopRuntime(ctx) {
  if (!ctx || typeof ctx.get !== 'function') return null
  for (const key of ['desktopRuntime', 'desktopActions']) {
    let value
    try {
      value = ctx.get(key)
    } catch {
      value = undefined
    }
    if (value && typeof value.requestRestart === 'function') return value
  }
  return null
}

/** 运行环境快照：诊断和 status 都靠它。 */
export function describeEnvironment(ctx) {
  const exe = desktopExecutable()
  const electron = process.versions.electron || ''
  return {
    ok: true,
    surface: exe || electron ? 'desktop' : 'web',
    pid: process.pid,
    ppid: process.ppid,
    execPath: process.execPath,
    argv: process.argv.slice(0, 8),
    cwd: process.cwd(),
    platform: process.platform,
    node: process.versions.node,
    electron: electron || null,
    desktopExe: exe,
    desktopRuntime: Boolean(desktopRuntime(ctx)),
    dshHome: dshHome(),
    logPath: path.join(dshHome(), 'logs', 'restart.log'),
  }
}

function quote(value) {
  return JSON.stringify(String(value))
}

/**
 * wscript 重启脚本。全 ASCII 是刻意的：wscript 读脚本按 ANSI 解释，
 * 混进中文会在没有 BOM 的机器上炸掉。
 */
function buildScript({ exe, delayMs, logPath, reason, resources }) {
  return [
    '// DeepSeek Harness restart helper (generated by dsh-restart-yashua)',
    'var EXE = ' + quote(exe) + ';',
    'var RES = ' + quote(resources || '') + ';',
    'var LOG = ' + quote(logPath) + ';',
    'var DELAY = ' + Number(delayMs) + ';',
    'var REASON = ' + quote(reason) + ';',
    'var fso = new ActiveXObject("Scripting.FileSystemObject");',
    'var sh = new ActiveXObject("WScript.Shell");',
    'function log(m) {',
    '  try {',
    '    var f = fso.OpenTextFile(LOG, 8, true);',
    '    f.WriteLine(new Date().toISOString() + " [" + REASON + "] " + m);',
    '    f.Close();',
    '  } catch (e) {}',
    '}',
    'function samePath(a, b) {',
    '  if (!a || !b) return false;',
    '  return String(a).replace(/\\//g, "\\\\").toLowerCase() === String(b).replace(/\\//g, "\\\\").toLowerCase();',
    '}',
    'function hostPids() {',
    '  var out = [];',
    '  try {',
    '    var wmi = GetObject("winmgmts:\\\\.\\root\\cimv2");',
    '    var it = new Enumerator(wmi.ExecQuery("SELECT ProcessId, ExecutablePath FROM Win32_Process WHERE Name=\'DeepSeek Harness.exe\' OR Name=\'DSH Desktop.exe\'"));',
    '    for (; !it.atEnd(); it.moveNext()) {',
    '      var p = it.item();',
    '      if (samePath(p.ExecutablePath, EXE)) out.push(p.ProcessId);',
    '    }',
    '  } catch (e) {',
    '    log("wmi failed: " + e.message);',
    '  }',
    '  return out;',
    '}',
    'try { sh.Environment("PROCESS").Remove("ELECTRON_RUN_AS_NODE"); } catch (e) {}',
    'log("begin exe=" + EXE);',
    'WScript.Sleep(DELAY);',
    'var list = hostPids();',
    'log("pids=" + list.join(","));',
    'for (var i = 0; i < list.length; i++) {',
    '  try { sh.Run("taskkill.exe /F /PID " + list[i], 0, true); } catch (e) { log("kill " + list[i] + " failed"); }',
    '}',
    'var deadline = new Date().getTime() + 30000;',
    'var left = list;',
    'while (new Date().getTime() < deadline) {',
    '  left = hostPids();',
    '  if (left.length === 0) break;',
    '  WScript.Sleep(250);',
    '}',
    'log("left=" + left.length);',
    'if (left.length > 0) {',
    '  log("abort: survivors " + left.join(","));',
    '} else {',
    '  // 若宿主已经被解开到 resources\\app，就在启动前把 app.asar 让位，否则 Electron 仍优先加载 asar，',
    '  // 打进去的补丁等于白打。条件不满足（没解包 / 没有 asar）就什么都不做，绝不制造半截状态。',
    '  if (RES) {',
    '    var APPMAIN = RES + "\\\\app\\\\lib\\\\main.js";',
    '    var ASAR = RES + "\\\\app.asar";',
    '    var BAK = RES + "\\\\app.asar.bak";',
    '    if (fso.FileExists(APPMAIN) && fso.FileExists(ASAR)) {',
    '      try { if (fso.FileExists(BAK)) fso.DeleteFile(BAK, true); } catch (e) {}',
    '      var moved = false;',
    '      for (var t = 0; t < 40; t++) {',
    '        try { fso.MoveFile(ASAR, BAK); moved = true; break; } catch (e) { WScript.Sleep(250); }',
    '      }',
    '      log("asar swap: " + (moved ? "ok" : "failed (asar kept)"));',
    '    } else {',
    '      log("asar swap: skipped (no unpacked app or no asar)");',
    '    }',
    '  }',
    '  try {',
    '    sh.Run("\\"" + EXE + "\\"", 1, false);',
    '    log("started");',
    '  } catch (e) {',
    '    log("start failed: " + e.message);',
    '  }',
    '}',
    '',
  ].join('\r\n')
}

function spawnDesktopRestart({ exe, delayMs, reason }) {
  const logDir = path.join(dshHome(), 'logs')
  fs.mkdirSync(logDir, { recursive: true })
  const logPath = path.join(logDir, 'restart.log')
  const scriptPath = path.join(os.tmpdir(), 'dsh-restart-' + process.pid + '-' + Date.now() + '.js')
  const resources = path.join(path.dirname(exe || ''), 'resources')
  fs.writeFileSync(scriptPath, buildScript({ exe, delayMs, logPath, reason, resources }), 'utf8')

  const env = { ...process.env }
  delete env.ELECTRON_RUN_AS_NODE
  delete env.DSH_PERMISSION_MODE

  const child = spawn('wscript.exe', ['//nologo', '//B', scriptPath], {
    detached: true,
    stdio: 'ignore',
    windowsHide: true,
    env,
  })
  child.on('error', () => {})
  child.unref()

  return { mode: 'desktop-script', script: scriptPath, logPath, exe, delayMs }
}

/**
 * 计划任务通道的批处理脚本。
 *
 * 为什么不用 wscript：宿主进程处于一个 Windows job object 里，从它 spawn 出去的
 * 进程（detached + unref 也一样）在几乎同一时刻就被 job 收割，连 WScript.Sleep
 * 都到不了。实测：普通子进程存活率 0，计划任务 100%。Task Scheduler 服务创建的
 * 进程不在我们的 job 内，这是唯一可靠的跳出方式。
 *
 * 全 ASCII 输出，cmd 按 ANSI 读脚本，混中文在无 BOM 环境会炸。
 */
function buildCmdScript({ exe, logPath, resources, taskName, delayMs }) {
  const asar = path.join(resources || '', 'app.asar')
  const bak = `${asar}.bak`
  const appMain = path.join(resources || '', 'app', 'lib', 'main.js')
  const ticks = Math.max(1, Math.round((Number(delayMs) || 1200) / 1000) + 1)
  return [
    '@echo off',
    'setlocal enabledelayedexpansion',
    `set LOG="${logPath}"`,
    'echo [%DATE% %TIME%] begin >> %LOG%',
    `ping -n ${ticks + 1} 127.0.0.1 >nul`,
    'taskkill /F /IM "DeepSeek Harness.exe" >> %LOG% 2>&1',
    'set /a n=0',
    ':wait',
    'ping -n 2 127.0.0.1 >nul',
    'set /a n+=1',
    'tasklist /FI "IMAGENAME eq DeepSeek Harness.exe" 2>nul | find /I "DeepSeek Harness.exe" >nul',
    'if not errorlevel 1 if !n! LSS 40 goto wait',
    `if exist "${appMain}" if exist "${asar}" (`,
    `  if exist "${bak}" del /f /q "${bak}" >nul 2>&1`,
    `  move /y "${asar}" "${bak}" >> %LOG% 2>&1`,
    '  echo asar swapped >> %LOG%',
    ')',
    // 用 explorer 启动而不是 start：start 会让 GUI 继承这条 cmd 的控制台，
    // 于是 host 进程的 stdout 全跑到一个残留的 cmd 窗口里（关掉它还会连带杀死 host）。
    // explorer 由外壳创建进程，不继承控制台，窗口也就不会留下来。
    `explorer.exe "${exe}"`,
    'echo started >> %LOG%',
    `schtasks /delete /tn "${taskName}" /f >> %LOG% 2>&1`,
    '',
  ].join('\r\n')
}

/** 用一次性计划任务执行重启：Task Scheduler 启动，逃出宿主的 job object。 */
function spawnViaTask({ exe, delayMs, reason }) {
  const home = dshHome()
  const logDir = path.join(home, 'logs')
  fs.mkdirSync(logDir, { recursive: true })
  const logPath = path.join(logDir, 'restart.log')
  const resources = path.join(path.dirname(exe || ''), 'resources')
  const taskName = 'dsh-restart-' + process.pid
  const stamp = `${process.pid}-${Date.now()}`
  const scriptPath = path.join(logDir, `restart-${stamp}.cmd`)
  const wrapperPath = path.join(logDir, `restart-${stamp}.vbs`)
  fs.writeFileSync(scriptPath, buildCmdScript({ exe, logPath, resources, taskName, delayMs }), 'ascii')
  // 计划任务直接执行 .cmd 会拉起一个控制台窗口；Windows 11 的默认终端是 Windows
  // Terminal，它跑完脚本后还会把窗口留着（标题就是 cmd.exe），看起来像重启没生效。
  // 所以计划任务只跑一个 wscript 包装器，由它在隐藏窗口里执行 cmd。
  fs.writeFileSync(
    wrapperPath,
    ['Set sh = CreateObject("WScript.Shell")', `sh.Run "cmd /c ""${scriptPath}""", 0, False`, ''].join('\r\n'),
    'ascii',
  )

  // /st 必须是未来时间，否则 create 会拒；真正触发靠 /run，与 /st 无关。
  const when = new Date(Date.now() + 5 * 60 * 1000)
  const st = `${String(when.getHours()).padStart(2, '0')}:${String(when.getMinutes()).padStart(2, '0')}`
  const tr = `wscript.exe //B //Nologo "${wrapperPath}"`
  execFileSync('schtasks.exe', ['/create', '/tn', taskName, '/tr', tr, '/sc', 'once', '/st', st, '/f'], { windowsHide: true, stdio: 'ignore' })
  execFileSync('schtasks.exe', ['/run', '/tn', taskName], { windowsHide: true, stdio: 'ignore' })

  return { mode: 'scheduled-task', script: scriptPath, wrapper: wrapperPath, logPath, exe, delayMs, taskName, reason }
}

/**
 * 请求重启。返回时进程通常还活着，真正的杀/拉在计划任务里执行，
 * 这样调用方（tool 结果、HTTP 响应）有机会先送达。
 */
export async function requestRestart(ctx, options = {}) {
  const delayMs = Math.max(0, Number(options.delayMs ?? 1200) || 0)
  const reason = String(options.reason || 'manual')
  const environment = describeEnvironment(ctx)

  const runtime = desktopRuntime(ctx)
  if (runtime) {
    try {
      await runtime.requestRestart()
      return { ok: true, mode: 'desktop-runtime', delayMs: 0, environment }
    } catch (error) {
      // 落到脚本层，把原因带回去便于排查
      const fallback = spawnDesktopRestart({ exe: environment.desktopExe, delayMs, reason })
      return { ok: true, ...fallback, warning: 'requestRestart failed: ' + String(error && error.message ? error.message : error), environment }
    }
  }

  if (!environment.desktopExe) {
    return {
      ok: false,
      mode: 'none',
      error: '未找到 DeepSeek Harness.exe，当前不是桌面安装形态：请在启动它的终端里手动重启。',
      environment,
    }
  }

  const plan = (() => {
    try {
      return { ok: true, ...spawnViaTask({ exe: environment.desktopExe, delayMs, reason }) }
    } catch (taskError) {
      try {
        const fallback = spawnDesktopRestart({ exe: environment.desktopExe, delayMs, reason })
        return {
          ok: true,
          ...fallback,
          warning: 'scheduled task failed: ' + String(taskError && taskError.message ? taskError.message : taskError),
        }
      } catch (scriptError) {
        return {
          ok: false,
          mode: 'none',
          error:
            '两条重启通道都失败。计划任务: ' + String(taskError && taskError.message ? taskError.message : taskError) +
            '；wscript: ' + String(scriptError && scriptError.message ? scriptError.message : scriptError),
        }
      }
    }
  })()
  return { ...plan, environment }
}

/** status 的一行摘要，tool 和 HTTP 共用。 */
export function summarize(environment) {
  return [
    '环境: ' + environment.surface + (environment.desktopRuntime ? ' / 桌面运行时可用' : ''),
    '进程: pid=' + environment.pid + ' ppid=' + environment.ppid,
    '可执行: ' + environment.execPath,
    '桌面 exe: ' + (environment.desktopExe || '(未找到)'),
    'Electron: ' + (environment.electron || '(无)') + ' / Node ' + environment.node,
    '日志: ' + environment.logPath,
  ].join('\n')
}
